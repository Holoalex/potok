/** Иконка счёта по названию — групп в экспорте нет, ориентируемся на имя. */
export function iconForAccount(name, kind = 'regular') {
  if (kind === 'goal') return 'piggy-bank';
  const lower = (name || '').toLowerCase();
  if (lower.includes('карт')) return 'credit-card';
  if (lower.includes('наличн')) return 'banknote';
  return 'wallet';
}
